// Pages builds are immutable per commit. Give each deployed commit its own notice.
// If the curated notes weren't updated, use actual commit titles instead of stale notes.
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { RELEASE } from '../js/data/release.js';

const git = (...args) => execFileSync('git', args, { encoding: 'utf8' }).trim();
let before = '';
try {
  const event = JSON.parse(await readFile(process.env.GITHUB_EVENT_PATH, 'utf8'));
  if (/^[a-f0-9]{40}$/i.test(event.before || '') && !/^0+$/.test(event.before)) before = event.before;
} catch { /* workflow_dispatch or local build */ }
if (!before || before === process.env.GITHUB_SHA) {
  try { before = git('rev-parse', 'HEAD^'); } catch { before = ''; }
}
let curated = true;
if (before) {
  try { curated = !!git('diff', '--name-only', before, 'HEAD', '--', 'js/data/release.js'); }
  catch { before = ''; }
}
let release = RELEASE;
if (!curated) {
  const range = before ? `${before}..HEAD` : 'HEAD';
  const messages = git('log', '-5', '--format=%s%x1f%b%x1e', range).split('\x1e').map((entry) => {
    const [subject = '', body = ''] = entry.trim().split('\x1f');
    return (/^Merge (?:pull request|branch)/i.test(subject) ? body.trim().split('\n')[0] || subject : subject).trim();
  }).filter(Boolean);
  release = { title: 'Latest update', changes: messages.length ? messages : ['The site has been updated.'] };
}
const sha = process.env.GITHUB_SHA || git('rev-parse', 'HEAD');
if (!/^[a-f0-9]{40}$/i.test(sha)) throw new Error('Invalid release commit ID');
const data = { id: sha, title: release.title, changes: release.changes };
await writeFile('_site/js/data/release.js', `// Generated by the Pages deployment.\nexport const RELEASE = Object.freeze(${JSON.stringify(data, null, 2)});\n`);
console.log(`Stamped release ${sha.slice(0, 7)} with ${curated ? 'curated notes' : 'commit summaries'}.`);
