import assert from 'node:assert/strict';
const data = new Map();
globalThis.localStorage = { getItem: (k) => data.get(k) ?? null, setItem: (k, v) => data.set(k, String(v)), removeItem: (k) => data.delete(k) };
const notices = [];
globalThis.CustomEvent = class { constructor(type, options) { this.type = type; this.detail = options.detail; } };
globalThis.window = { dispatchEvent: (event) => notices.push(event) };
localStorage.setItem('nx:marks', JSON.stringify({ 'anime:42': [1, 2], 'manga:abc': ['3'] }));
const p = await import('../js/profile.js');
assert.equal(p.getProfile().xp, 50, 'migrate existing marks without notices');
assert.equal(notices.length, 0);
const id = p.getProfile().id;
assert.ok(id.length >= 8);
assert.equal(p.recordCompletions('anime', 42, [1]).xp, 50, 'existing completion is not credited twice');
assert.equal(p.recordCompletions('anime', 42, [3, 4, 5]).xp, 110);
assert.equal(p.getProfile().level, 2);
assert.equal(notices.length, 1);
assert.equal(notices[0].detail.level, 2);
assert.equal(p.recordCompletions('anime', 42, [3]).xp, 110, 'repeat completion is not credited');
assert.equal(p.levelForXP(99), 1);
assert.equal(p.levelForXP(100), 2);
assert.equal(p.levelForXP(299), 2);
assert.equal(p.levelForXP(300), 3);
assert.equal(p.xpForLevel(3), 300);
assert.equal(p.setProfileName('  A reader  ').name, 'A reader');
const backup = p.exportProfile();
assert.equal(backup.id, undefined, 'a backup does not transfer the installation ID');
p.recordCompletions('manga', 'another', ['8']);
p.importProfile(backup, { merge: true });
assert.equal(p.getProfile().xp, 120, 'merge keeps local and imported events');
p.importProfile(backup, { merge: false });
assert.equal(p.getProfile().xp, 110, 'replace restores imported events');
assert.equal(p.getProfile().id, id, 'import retains local installation ID');
p.importProfile({ name: 'evil', earned: { '["invalid","x","y"]': true, '["anime","x","y"]': 'true' } }, { merge: false });
assert.equal(p.getProfile().xp, 0, 'malformed backup events are ignored');
assert.ok(p.titleFor(10, 10, 0).includes('Scene'));
assert.ok(p.titleFor(10, 0, 10).includes('Lore'));
p.resetProfile();
assert.notEqual(p.getProfile().id, id, 'reset changes installation ID');
console.log('Local profile, migration, deduplication, backup and level checks passed');
